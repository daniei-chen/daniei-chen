#!/usr/bin/env python3
"""Build the coastal profile without repainting its checked-in artwork.

Only the public repository index is data driven. The visual assets are original
illustrations checked into assets/coastal and are never replaced by the daily job.
"""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data/profile.json"
OUT = ROOT / "README.md"
OWNER = "daniei-chen"
FEATURED = (
    ("ZCode-App", "ZCode App", "sea-window.png", "扫码连接 ZCode，把桌面任务与会话带到手机上。", "ZCode-App：一扇面向蓝色海面的白色窗户"),
    ("Little-Whale", "小鲸鱼", "soft-wave.png", "本地解析与下载视频，把喜欢的片段留在身边。", "Little-Whale：轻柔卷起的蓝白色海浪"),
    ("dsh-token-insight", "DSH Token Insight", "notebook.png", "从 Token 到会话趋势，记录 DSH 的本地使用。", "dsh-token-insight：白色手记与一支蓝色铅笔"),
)
GATEWAYS = (
    ("zhihui-gateway", "智汇", "zhihui-lighthouse.png", "让灵感出发，让工作向前。", "WorkBuddy、Qoder、Trae 的统一工作台。", "访问网站", "https://zhihui.kaogong.art/", "智汇 zhihui-gateway：白色灯塔、帆船与蓝色海岸"),
    ("zhijing-gateway", "智境", "zhijing-terrace.png", "复杂有序，智能从容。", "AI 网关的登录、成员与管理前端。", "界面一览", "https://github.com/daniei-chen/zhijing-gateway#界面一览", "智境 zhijing-gateway：面向海面的白色阅读露台"),
)


def repo_url(name: str) -> str:
    return f"https://github.com/{OWNER}/{name}"


def gateway_gallery() -> list[str]:
    parts = ["<table>", "  <tr>"]
    for name, label, image, tagline, description, action, target, alt in GATEWAYS:
        parts.extend([
            '    <td width="50%" valign="top">',
            f'      <a href="{repo_url(name)}"><img src="assets/coastal/{image}" width="100%" alt="{alt}"></a>',
            f'      <h3><a href="{repo_url(name)}">{label}</a></h3>',
            f"      <p><strong>{tagline}</strong></p>",
            f"      <p>{description}</p>",
            f'      <p><a href="{target}">{action}</a> · <a href="{repo_url(name)}">查看项目</a></p>',
            "    </td>",
        ])
    parts.extend(["  </tr>", "</table>"])
    return parts


def project_list() -> list[str]:
    """Keep secondary projects readable without squeezing three mobile columns."""
    parts = []
    for name, label, image, description, alt in FEATURED:
        parts.extend([
            f'<a href="{repo_url(name)}"><img src="assets/coastal/{image}" align="right" width="28%" alt="{alt}"></a>',
            "",
            f"### [{label}]({repo_url(name)})",
            "",
            description,
            "",
            f"[了解项目]({repo_url(name)}) · [下载版本]({repo_url(name)}/releases)",
            "",
            '<br clear="all">',
            "",
        ])
    return parts


def remaining_repos(data: dict) -> list[dict]:
    """Keep new public repositories discoverable without cluttering the hero."""
    shown = {OWNER, *(r[0] for r in FEATURED), *(r[0] for r in GATEWAYS)}
    result = []
    for repo in data.get("repos", []):
        name = str(repo.get("name", ""))
        url = str(repo.get("url", ""))
        parsed = urlparse(url)
        if name in shown or parsed.scheme != "https" or parsed.netloc != "github.com":
            continue
        if parsed.path != f"/{OWNER}/{name}":
            continue
        result.append(repo)
    return sorted(result, key=lambda r: str(r["name"]).casefold())


def build(data: dict) -> str:
    parts = [
        "<!-- Generated by tools/make_readme.py. Edit the generator, not this file. -->",
        "",
        '<picture>',
        '  <source media="(max-width: 640px)" srcset="assets/coastal/coastal-hero-mobile.png">',
        '  <img src="assets/coastal/coastal-hero.png" width="100%" alt="Daniei Chen · 让想法慢慢长大。写一点代码，做一些喜欢的东西。蓝色海面上有一叶帆船，小鸟沿白色海岸骑行。">',
        "</picture>",
        "",
        '<p align="center">独立开发者。做一些有用的东西，也给创造留一点快乐。</p>',
        "",
        f'<p align="center"><a href="#最近在做">看看作品</a> · <a href="#一点关于我">关于我</a> · <a href="https://github.com/{OWNER}?tab=repositories">全部仓库</a></p>',
        "",
        "## 最近在做",
        "",
    ]
    parts.extend(gateway_gallery())
    parts.extend(["", "## 一些小作品", "", "从远程任务，到日常记录。为遇到的小需求，做一些顺手的东西。", ""])
    parts.extend(project_list())
    parts.extend([
        "## 一点关于我",
        "",
        "用 Flutter / Dart 做移动应用，也写 Go、Python 和 TypeScript。喜欢把原型慢慢打磨成作品，让功能与细节一起变好。",
        "",
        "偏爱蓝与白，也偏爱有呼吸感的界面。欢迎到对应项目的 Issues，聊聊你的想法。",
    ])
    extra = remaining_repos(data)
    if extra:
        parts.extend(["", "<details>", "  <summary>更多仓库与小实验</summary>", "", "  <ul>"])
        for repo in extra:
            name = html.escape(str(repo["name"]))
            url = html.escape(str(repo["url"]), quote=True)
            suffix = " · 筹备中" if repo.get("empty") else " · fork" if repo.get("fork") else ""
            parts.append(f'    <li><a href="{url}">{name}</a>{suffix}</li>')
        parts.extend(["  </ul>", "</details>"])
    parts.extend([
        "",
        "---",
        "",
        '<p align="center">谢谢你来这里。愿你的想法，也慢慢长大。</p>',
    ])
    return "\n".join(parts) + "\n"


def validate_assets() -> None:
    names = ["coastal-hero.png", "coastal-hero-mobile.png", *(r[2] for r in GATEWAYS), *(r[2] for r in FEATURED)]
    missing = [name for name in names if not (ROOT / "assets/coastal" / name).is_file()]
    if missing:
        raise SystemExit("Missing coastal artwork: " + ", ".join(missing))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check assets and README regeneration without writing.")
    args = parser.parse_args()
    validate_assets()
    content = build(json.loads(DATA.read_text(encoding="utf-8")))
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != content:
            raise SystemExit("README.md is stale; run python tools/make_readme.py")
        print("Profile artwork and README regeneration: OK")
    else:
        OUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"Updated {OUT.name}; original coastal artwork preserved")


if __name__ == "__main__":
    main()
